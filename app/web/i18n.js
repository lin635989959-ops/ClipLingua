function _detectUiLang() {
  const saved = (() => { try { return localStorage.getItem("ui.lang"); } catch { return null; } })();
  if (saved && SUPPORTED_UI_LANGS.includes(saved)) return saved;
  const nav = (navigator.language || "en").toLowerCase().split("-")[0];
  return SUPPORTED_UI_LANGS.includes(nav) ? nav : "en";
}

let _UI_LANG = _detectUiLang();
document.documentElement.lang = _UI_LANG === "zh" ? "zh-CN" : _UI_LANG;

function uiLang() { return _UI_LANG; }
function setUiLang(code) {
  if (!SUPPORTED_UI_LANGS.includes(code)) return;
  _UI_LANG = code;
  try { localStorage.setItem("ui.lang", code); } catch {}
  location.reload();
}

function t(key, vars) {
  const dict = I18N[_UI_LANG] || I18N.en;
  let str = dict[key] ?? I18N.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replaceAll(`{${k}}`, String(v ?? ""));
    }
  }
  return str;
}

function langMeta(code) {
  return LANG_META[code] || LANG_META.sv;
}

function langName(code) {
  return t(`lang_${langMeta(code).code}`);
}

function posName(code) {
  if (!code) return "";
  const k = `pos_${code}`;
  return (I18N[_UI_LANG]?.[k] || I18N.en[k] || code);
}

function uiLangPickerHtml() {
  const cur = uiLang();
  const opts = [["zh", "中文"], ["en", "EN"], ["es", "ES"], ["sv", "SV"]];
  return `<select class="ui-lang-select" data-ui-lang aria-label="Interface language">
    ${opts.map(([c, lbl]) => `<option value="${c}" ${c === cur ? "selected" : ""}>🌐 ${lbl}</option>`).join("")}
  </select>`;
}

function mountUiLangPicker() {
  document.querySelectorAll("[data-ui-lang-slot]").forEach(slot => {
    slot.innerHTML = uiLangPickerHtml();
    slot.querySelector("[data-ui-lang]")?.addEventListener("change", e => setUiLang(e.target.value));
  });
}

function applyStaticI18n(root = document) {
  root.querySelectorAll("[data-i18n]").forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-html]").forEach(el => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  root.querySelectorAll("[data-i18n-ph]").forEach(el => {
    el.placeholder = t(el.dataset.i18nPh);
  });
  root.querySelectorAll("[data-i18n-title]").forEach(el => {
    el.title = t(el.dataset.i18nTitle);
  });
}
